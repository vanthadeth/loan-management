// Bundles scripts/contract-kit.ts (and the shared contract code it imports from ../src) into one HTML page
// for the contract WebView: src/contract/kit.generated.ts. Runs after npm install; rerun with `npm run contract-kit`.
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const out = await build({
  entryPoints: [here('./contract-kit.ts')], bundle: true, write: false, format: 'iife', target: 'es2019', minify: true, legalComments: 'none',
})
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
const html = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' +
  '<style>html,body{margin:0;background:transparent}#box{padding:8px;overflow:hidden}#doc{border:0;background:#fff;width:816px;height:1100px;transform-origin:top left;display:block}</style>' +
  '</head><body><div id="box"><iframe id="doc" sandbox="allow-same-origin"></iframe></div><script>' + js + '</script></body></html>'
writeFileSync(here('../src/contract/kit.generated.ts'), '// Generated by scripts/build-contract-kit.mjs; do not edit.\nexport const KIT_HTML = ' + JSON.stringify(html) + '\n')
console.log('contract kit:', Math.round(html.length / 1024), 'KB')
